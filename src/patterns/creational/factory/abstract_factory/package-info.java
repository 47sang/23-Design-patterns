/**
 * 抽象工厂模式（Abstract Factory Pattern）
 *
 * <h2>模式说明</h2>
 * <p>抽象工厂模式提供一个创建<strong>一系列相关或相互依赖的对象</strong>的接口，
 * 而无需指定它们具体的类。它是对工厂方法模式的进一步抽象，
 * 适用于需要创建"产品族"而非单个产品的场景。</p>
 *
 * <h2>产品族 vs 产品等级结构</h2>
 * <pre>
 * 产品等级结构：同一类型的产品 hierarchy（如手机、平板、笔记本 —— 不同类别）
 * 产品族：同一品牌/主题下的多个产品（如小米手机 + 小米平板 + 小米路由器）
 *
 *             ┌─────────────────────────────────┐
 *             │       AbstractFactory            │
 *             │  + createPhone() + createPad()   │
 *             │  + createRouter()                │
 *             └──────────────┬──────────────────┘
 *                            │ 继承
 *           ┌────────────────┼────────────────┐
 *           │                │                │
 *     ┌─────┴─────┐   ┌─────┴─────┐   ┌─────┴─────┐
 *     │XiaoMiFactory│ │HuaweiFactory│ │AppleFactory│
 *     └─────┬─────┘   └─────┬─────┘   └─────┬─────┘
 *           │                │                │
 *      ┌────┴────┐      ┌────┴────┐      ┌────┴────┐
 *      │小米手机  │      │华为手机  │      │苹果手机  │  ← 同属"手机"产品等级
 *      │小米平板  │      │华为平板  │      │苹果平板  │
 *      │小米路由器│      │华为路由器│      │苹果路由器│
 *      └─────────┘      └─────────┘      └─────────┘
 *       ↑ 同一工厂创建的产品属于同一个"产品族"，保证风格一致
 * </pre>
 *
 * <h2>核心思想</h2>
 * <p>抽象工厂把 Related Product 的创建逻辑封装在一起，
 * 保证客户端获取到的产品都是兼容的（属于同一个产品族）。
 * 新增产品族只需新增一个工厂子类；
 * 新增产品等级（如新增"智能手表"）需要修改抽象工厂接口及所有子类。</p>
 *
 * <h2>优缺点</h2>
 * <ul>
 *   <li><strong>优点</strong>：保证产品的一致性（同一工厂的产品风格统一）；隔离了具体类的依赖</li>
 *   <li><strong>缺点</strong>：新增产品等级（产品种类）困难，需要修改抽象工厂及所有实现</li>
 * </ul>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>UI 主题系统：深色主题、浅色主题各提供一套统一的 UI 组件</li>
 *   <li>数据库访问：不同数据库厂商的 DAO 工厂（MySQL、Oracle、PostgreSQL）</li>
 *   <li>跨平台 GUI：Windows、Mac、Linux 各自提供一套组件</li>
 * </ul>
 *
 * @see patterns.creational.factory.simple 简单工厂模式
 * @see patterns.creational.factory.method 工厂方法模式
 */
