/**
 * 简单工厂模式（Simple Factory Pattern）
 *
 * <h2>模式说明</h2>
 * <p>简单工厂模式通过一个工厂类来创建各种产品对象，
 * 客户端不需要知道具体产品类的创建逻辑。</p>
 *
 * <h2>结构</h2>
 * <pre>
 *           ┌─────────────────┐
 *           │   FruitFactory  │  ← 工厂类（核心，根据参数决定创建哪种产品）
 *           │  + getFruit()   │
 *           └────────┬────────┘
 *                    │ 创建
 *           ┌────────┴────────┐
 *           │    Fruit        │  ← 抽象产品类
 *           │   (abstract)    │
 *           └────────┬────────┘
 *          ┌─────────┼──────────┐
 *          │         │          │
 *       ┌──┴──┐   ┌─┴─┐    ┌──┴──┐
 *       │Apple│   │Banana│  │Orange│  ← 具体产品类
 *       └─────┘   └────┘   └─────┘
 * </pre>
 *
 * <h2>优缺点</h2>
 * <ul>
 *   <li><strong>优点</strong>：客户端无需知道具体产品类名；实现了对象创建和使用的分离</li>
 *   <li><strong>缺点</strong>：工厂类职责过重，违反单一职责原则；新增产品需要修改工厂类，违反开闭原则</li>
 * </ul>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>日志记录器：根据配置创建不同类型的日志记录器（文件、数据库、控制台）</li>
 *   <li>数据库连接：根据配置创建不同数据库的连接对象</li>
 *   <li>消息推送：根据平台类型创建不同的推送服务</li>
 * </ul>
 *
 * @see patterns.creational.factory.method 工厂方法模式是对简单工厂的改进
 */
