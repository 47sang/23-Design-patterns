/**
 * 命令模式（Command Pattern）
 *
 * <h2>模式说明</h2>
 * <p>将一个请求封装为一个对象，从而可用不同的请求对客户进行参数化，
 * 对请求排队或记录请求日志，以及支持可撤销的操作。</p>
 *
 * <h2>现实类比</h2>
 * <p>餐厅里的点菜单：</p>
 * <pre>
 * 顾客（Client）→ 告诉服务员（Invoker）要什么
 * 服务员不自己做菜，而是把请求写在点菜单上（Command）
 * 厨师（Receiver）拿到点菜单后执行具体的做菜动作
 *
 * 这样做的好处：
 *   - 服务员不需要知道怎么做菜（解耦）
 *   - 可以把点菜单保存下来（撤销/重做、日志记录）
 *   - 可以批量处理多个请求（排队执行）
 * </pre>
 *
 * <h2>结构</h2>
 * <pre>
 *   ┌──────────────┐      ┌──────────────┐
 *   │   Client     │      │  Invoker     │
 *   │  (创建命令)  │─────►│  (调用命令)  │
 *   └──────────────┘      └──────┬───────┘
 *                                │ execute()
 *                         ┌──────┴───────┐
 *                         │  Command     │  ← 抽象命令
 *                         │  + execute() │
 *                         └──────┬───────┘
 *                                │ 实现
 *                         ┌──────┴───────┐
 *                         │ConcreteCommand│ ← 持有 Receiver 引用
 *                         │  + execute()  │    调用 receiver.action()
 *                         └───────────────┘
 *
 *   ┌──────────────┐
 *   │  Receiver    │  ← 真正执行操作的对象（如空调、灯光）
 *   │  + action()  │
 *   └──────────────┘
 * </pre>
 *
 * <h2>命令模式的额外能力</h2>
 * <ul>
 *   <li><strong>撤销（Undo）</strong>：命令对象保存执行前的状态，undo() 时恢复</li>
 *   <li><strong>重做（Redo）</strong>：撤销后可以重新执行</li>
 *   <li><strong>宏命令（Macro Command）</strong>：一个命令组合多个命令</li>
 *   <li><strong>延迟执行</strong>：命令可以先排队，在合适的时候再执行</li>
 *   <li><strong>日志记录</strong>：将命令持久化，系统崩溃后可以恢复执行</li>
 * </ul>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>GUI：菜单项、按钮的点击事件</li>
 *   <li>事务操作：数据库事务的提交和回滚</li>
 *   <li>任务调度：后台任务的封装和执行</li>
 *   <li>智能家居：遥控器上的按钮对应不同的设备操作</li>
 * </ul>
 *
 * @see patterns.behavioral.command 命令模式示例
 */
