/**
 * 中介者模式（Mediator Pattern）
 *
 * <h2>模式说明</h2>
 * <p>定义一个中介对象来简化原有对象之间的交互关系。
 * 中介者使各对象不需要显式地相互引用，
 * 从而使其耦合松散，而且可以独立地改变它们之间的交互。</p>
 *
 * <h2>现实类比</h2>
 * <p>房产中介：</p>
 * <pre>
 * 没有中介的情况（N 个房东 + N 个买家）：
 *   每个房东要找所有买家 → 每个买家要找所有房东 → N² 次交互，混乱！
 *
 * 有中介的情况：
 *   房东只需要告诉中介"我要卖房"
 *   买家只需要告诉中介"我要买房"
 *   中介负责匹配双方 → 所有交互都经过中介，只需 2N 次交互
 * </pre>
 *
 * <h2>结构</h2>
 * <pre>
 *   ┌─────────────────────────────────────────────────┐
 *   │                   Mediator                       │
 *   │  中介者（定义同事对象之间的交互接口）              │
 *   └──────────────┬──────────────────────────────────┘
 *                  │ 知道
 *      ┌───────────┼───────────┐
 *      │           │           │
 *   ┌──┴──┐     ┌──┴──┐     ┌──┴──┐
 *   │Colleague│   │Colleague│   │Colleague│  ← 同事对象
 *   │  A     │   │  B     │   │  C     │      只和中介交互
 *   └───┬───┘   └───┬───┘   └───┬───┘
 *       │           │           │
 *       │   所有交互都通过中介转发   │
 *       └───────────┼───────────┘
 *                   │
 *             ┌─────┴─────┐
 *             │  Concrete  │  ← 具体中介者
 *             │ Mediator   │     协调所有同事对象
 *             └───────────┘
 * </pre>
 *
 * <h2>中介者 vs 观察者</h2>
 * <ul>
 *   <li><strong>中介者</strong>：同事对象之间<strong>不能直接通信</strong>，
 *       必须通过中介者——中介者是强制的、中心化的协调者</li>
 *   <li><strong>观察者</strong>：主题和观察者之间是<strong>松散的通知关系</strong>，
 *       主题只知道观察者的接口，不关心具体是谁——观察者是松散的订阅者</li>
 * </ul>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>聊天室：所有消息通过聊天室（中介者）转发给用户</li>
 *   <li>MVC 中的 Controller：协调 View 和 Model 之间的交互</li>
 *   <li>机场塔台：所有飞机的起飞/降落请求都通过塔台协调</li>
 * </ul>
 *
 * <h2>注意事项</h2>
 * <ul>
 *   <li>中介者容易变成"上帝类"——需要合理划分职责</li>
 *   <li>适合同事类数量多且交互复杂的场景；如果交互简单，中介者反而增加复杂度</li>
 * </ul>
 *
 * @see patterns.behavioral.mediator 中介者模式示例
 */
