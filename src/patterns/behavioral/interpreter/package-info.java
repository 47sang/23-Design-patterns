/**
 * 解释器模式（Interpreter Pattern）
 *
 * <h2>模式说明</h2>
 * <p>给定一个语言，定义它的文法的一种表示，并定义一个解释器，
 * 这个解释器使用该表示来解释语言中的句子。</p>
 *
 * <h2>适用场景</h2>
 * <p>当某个语言（或表达式）的语法规则比较简单，且执行效率不是核心瓶颈时，
 * 可以使用解释器模式来解析和执行。</p>
 *
 * <h2>核心组件</h2>
 * <ul>
 *   <li><strong>终结符表达式（Terminal Expression）</strong>：
 *       实现文法中的终结符（最基本的元素，如数字、变量）</li>
 *   <li><strong>非终结符表达式（Non-terminal Expression）</strong>：
 *       实现文法中的规则（如加法、减法、乘法），递归组合子表达式</li>
 *   <li><strong>上下文（Context）</strong>：
 *       包含解释器需要的信息（如变量值）</li>
 * </ul>
 *
 * <h2>结构</h2>
 * <pre>
 *              ┌───────────────────┐
 *              │  Expression       │  ← 抽象表达式
 *              │  + interpret()    │
 *              └────────┬──────────┘
 *                       │
 *          ┌────────────┼────────────┐
 *          │            │            │
 *   ┌──────┴─────┐ ┌───┴─────┐ ┌───┴─────┐
 *   │ Terminal   │ │NonTerm  │ │ NonTerm │
 *   │Expression  │ │Expression│ │Expr     │
 *   │(终结符)    │ │(非终结符)│ │(递归)   │
 *   └────────────┘ └────┬────┘ └────┬────┘
 *                       │ 组合       │ 组合
 *                  ┌────┴────┐  ┌──┴──┐
 *                  │子表达式1 │  │子表 │
 *                  │         │  │达式2│
 *                  └─────────┘  └─────┘
 * </pre>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>算术表达式求值：解析 "3 + 5 * (2 - 1)" 这样的表达式</li>
 *   <li>规则引擎：解析业务规则条件（如 "age > 18 && score > 60"）</li>
 *   <li>SQL 解析：简易 SQL 语句的解析和执行</li>
 * </ul>
 *
 * <h2>注意事项</h2>
 * <ul>
 *   <li>文法规则太复杂时，解释器模式会导致类爆炸，此时应使用 parser generator 工具</li>
 *   <li>解释器模式通常配合组合模式使用（表达式的递归结构）</li>
 *   <li>现代开发中，对于复杂的语法解析，通常使用 ANTLR、JavaCC 等工具</li>
 * </ul>
 *
 */
