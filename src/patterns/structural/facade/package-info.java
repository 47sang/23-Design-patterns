/**
 * 外观模式（Facade Pattern）
 *
 * <h2>模式说明</h2>
 * <p>为子系统中一组接口提供一个一致的界面，
 * 外观模式定义了一个高层接口，这个接口使这一子系统更加容易使用。</p>
 *
 * <h2>现实类比</h2>
 * <p>就像你去餐厅点一份"套餐"：
 * 你不需要知道后厨的切菜、炒菜、装盘分别由哪个厨师完成，
 * 你只需要告诉服务员"我要一份宫保鸡丁套餐"，
 * 服务员（Facade）会协调后厨的各个工序完成你的需求。</p>
 *
 * <h2>结构</h2>
 * <pre>
 *   ┌──────────────────────────────────────────────────┐
 *   │                    Facade                         │
 *   │  + simplifiedOperation()                         │
 *   │    内部依次调用 SubA、SubB、SubC 的方法           │
 *   └────────────┬─────────────────────────────────────┘
 *                │ 委托
 *     ┌──────────┼──────────┐
 *     │          │          │
 *  ┌──┴──┐   ┌──┴──┐   ┌──┴──┐
 *  │SubA │   │SubB │   │SubC │   ← 子系统（各自独立，不知道 Facade 的存在）
 *  └─────┘   └─────┘   └─────┘
 * </pre>
 *
 * <h2>核心思想</h2>
 * <ul>
 *   <li>Facade 知道哪些子系统类负责处理哪些请求</li>
 *   <li>Facade 将客户端的请求委派给适当的子系统对象</li>
 *   <li>客户端只需要和 Facade 交互，不需要了解子系统的内部结构</li>
 *   <li>子系统不需要知道 Facade 的存在</li>
 * </ul>
 *
 * <h2>外观 vs 中介者</h2>
 * <ul>
 *   <li><strong>外观</strong>：单向的，Facade 封装子系统，子系统不知道 Facade</li>
 *   <li><strong>中介者</strong>：双向的，各同事对象都知道中介者，中介者也认识所有同事</li>
 * </ul>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>API 网关：为多个微服务提供统一入口</li>
 *   <li>智能家居：一键"回家模式"同时控制灯光、空调、窗帘</li>
 *   <li>复杂第三方库的简化封装</li>
 * </ul>
 *
 * @see patterns.structural.facade 外观模式示例
 */
