/**
 * 适配器模式（Adapter Pattern）
 *
 * <h2>模式说明</h2>
 * <p>将一个类的接口转换成客户希望的另一个接口，
 * 使原本由于接口不兼容而不能一起工作的类可以一起工作。</p>
 *
 * <h2>适配器在现实中的类比</h2>
 * <p>就像你出国旅游时带的电源转换器：
 * 你的设备（三脚插头）不能直接插入国外的插座（两脚），
 * 转换器（适配器）夹在中间，两边都对接，让两者能够正常工作。</p>
 *
 * <h2>两种实现方式</h2>
 * <table>
 *   <tr>
 *     <th>类适配器</th>
 *     <th>对象适配器（推荐）</th>
 *   </tr>
 *   <tr>
 *     <td>通过继承被适配者 + 实现目标接口</td>
 *     <td>通过组合（持有被适配者引用）+ 实现目标接口</td>
 *   </tr>
 *   <tr>
 *     <td>Java 不支持多继承，只能适配一个类</td>
 *     <td>可以适配多个被适配者，更灵活</td>
 *   </tr>
 * </table>
 *
 * <h2>结构</h2>
 * <pre>
 *   ┌─────────────┐       ┌──────────────┐       ┌──────────────┐
 *   │   Target    │◄──────│   Adapter    │──────►│   Adaptee    │
 *   │ (目标接口)  │       │  (适配器)    │       │ (被适配者)    │
 *   └─────────────┘       └──────────────┘       └──────────────┘
 *        ▲                        │ 组合
 *   ┌────┴────┐            ┌──────┴──────┐
 *   │ Client  │            │  adaptee    │
 *   │(客户端) │            │  引用       │
 *   └────────┘            └─────────────┘
 * </pre>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>第三方 SDK 集成：统一不同支付 SDK 的接口</li>
 *   <li>数据格式转换：XML 与 JSON 数据格式的相互转换</li>
 *   <li>遗留系统集成：新系统与旧系统的接口适配</li>
 * </ul>
 *
 * @see patterns.structural.adapter 适配器示例（类适配器 + 对象适配器）
 */
