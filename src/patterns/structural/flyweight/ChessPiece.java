package patterns.structural.flyweight;

/**
 * 围棋棋子接口（享元 / Flyweight）
 *
 * <p>享元模式中的享元接口，定义了棋子的基本操作。
 * 棋子有两个维度的状态：<strong>内部状态</strong>和<strong>外部状态</strong>。</p>
 *
 * <h2>内部状态 vs 外部状态</h2>
 * <ul>
 *   <li><strong>内部状态（Intrinsic State）</strong>：
 *       不随环境变化而变化，可以共享的信息。
 *       在本例中：棋子的<strong>颜色</strong>（黑/白）、<strong>大小</strong>。
 *       这些信息存储在享元对象内部，所有引用该享元的客户端共享同一份内部状态。</li>
 *   <li><strong>外部状态（Extrinsic State）</strong>：
 *       随环境变化而变化，不可共享的信息。
 *       在本例中：棋子在棋盘上的<strong>坐标</strong>（x, y）。
 *       这些信息不由享元对象存储，而是通过方法参数传入，
 *       由客户端在调用时提供。</li>
 * </ul>
 *
 * <h2>为什么这样设计？</h2>
 * <p>围棋棋盘上有 361 个交叉点（19×19），一局棋可能需要放置 200+ 颗棋子。
 * 如果每颗棋子都是一个独立对象，需要 200+ 个对象。
 * 但棋盘上只有两种颜色的棋子（黑、白），所以通过共享：
 * <pre>
 * 内部状态（颜色）共享 → 只需 2 个享元对象
 * 外部状态（坐标）不共享 → 每次 place() 传入不同的 x, y
 * </pre>
 * 这样就大幅减少了内存占用。</p>
 *
 * <h2>与单例的区别</h2>
 * <ul>
 *   <li><strong>单例</strong>：一个类全局只有一个实例</li>
 *   <li><strong>享元</strong>：一个类可以有多个实例（如黑白各一个），
 *       但通过共享来减少总数。享元池中的对象数量取决于内部状态的不同取值数量</li>
 * </ul>
 *
 * @see ConcreteChessPiece 具体享元
 * @see ChessPieceFactory 享元工厂
 */
interface ChessPiece {

    /**
     * 放置棋子到指定坐标。
     *
     * <p>坐标（x, y）是<strong>外部状态</strong>，不作为对象的内部字段存储，
     * 而是通过方法参数传入。这样同一个享元对象可以在不同坐标被多次"放置"。</p>
     *
     * <p>外部状态通常由客户端维护，或者在方法调用时传入。
     * 本示例中简化处理，直接在方法中打印坐标信息。</p>
     *
     * @param x 棋子在棋盘上的横坐标（0-18）
     * @param y 棋子在棋盘上的纵坐标（0-18）
     */
    void place(int x, int y);
}
