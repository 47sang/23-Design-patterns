/**
 * 组合模式（Composite Pattern）
 *
 * <h2>模式说明</h2>
 * <p>将对象组合成树形结构以表示"部分-整体"的层次结构，
 * 使用户对<strong>单个对象</strong>和<strong>组合对象</strong>的使用具有一致性。</p>
 *
 * <h2>核心思想</h2>
 * <p>组合模式让客户端不必区分"叶子节点"和"容器节点"，
 * 都通过统一的接口来操作。客户端代码可以递归地处理整个树形结构，
 * 而无需关心当前操作的是叶子还是分支。</p>
 *
 * <h2>结构</h2>
 * <pre>
 *             ┌─────────────────┐
 *             │   Component     │  ← 抽象组件（统一接口）
 *             │  + add()        │
 *             │  + remove()     │
 *             │  + operation()  │
 *             └────────┬────────┘
 *                      │
 *          ┌───────────┼───────────┐
 *          │           │           │
 *     ┌────┴────┐ ┌───┴───┐ ┌────┴────┐
 *     │  Leaf   │ │Composite│ │ Composite│
 *     │ (叶子)  │ │ (容器)  │ │ (容器)   │
 *     └────┬────┘ └───┬────┘ └────┬────┘
 *          │        ┌──┴──┐      ┌──┴──┐
 *          │        │Leaf │      │Leaf │
 *          │        └─────┘      └─────┘
 *          └──────────────────────────────┘
 *               整个树结构被统一操作
 * </pre>
 *
 * <h2>透明组合 vs 安全组合</h2>
 * <ul>
 *   <li><strong>透明组合</strong>：Component 中声明 add/remove 等管理子节点的方法，
 *       叶子节点抛出异常。优点：客户端无需判断类型；缺点：叶子节点有不安全的方法</li>
 *   <li><strong>安全组合</strong>：只在 Composite 中声明 add/remove，
 *       Component 不声明。优点：接口更安全；缺点：客户端需要判断类型，失去透明性</li>
 * </ul>
 *
 * <h2>业务场景</h2>
 * <ul>
 *   <li>文件系统：文件和文件夹的统一处理</li>
 *   <li>组织架构：部门和员工的层次结构</li>
 *   <li>菜单系统：菜单项和子菜单的组合</li>
 * </ul>
 *
 * @see patterns.structural.composite 组合模式示例
 */
